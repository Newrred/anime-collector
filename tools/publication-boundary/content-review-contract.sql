reset role;
insert into private.memory_moderators(user_id) values('11111111-1111-4111-8111-111111111111');
set local role authenticated;
\ir content-initial-contract.sql
select pg_temp.fails($q$select public.review_memory_publication_content(current_setting('test.id')::uuid,repeat('0',64),'GENERAL',0,'TEST_ONLY_CONTENT')$q$,'PUBLICATION_CONFLICT','unseen snapshot cannot be approved');

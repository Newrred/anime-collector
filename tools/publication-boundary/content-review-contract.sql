select pg_temp.fails($q$select public.review_memory_publication_content(current_setting('test.id')::uuid,current_setting('test.content_hash'),'MATURE',0,'TEST_ONLY_CONTENT')$q$,'PUBLICATION_CONFLICT','stale moderation action rejected');

select pg_temp.ok(public.read_memory_publication(current_setting('test.id')::uuid) is null,'migration closes previously readable unclassified board before any policy setup');
update private.memory_publication_settings set content_policy_revision='TEST_ONLY_CONTENT';
select set_config('test.content_hash',(select encode(sha256(convert_to(published_snapshot::text,'UTF8')),'hex') from private.memory_publications where id=current_setting('test.id')::uuid),true);
set local role anon;
select pg_temp.ok(public.read_memory_publication(current_setting('test.id')::uuid) is null,'unreviewed board hides metadata and cards');

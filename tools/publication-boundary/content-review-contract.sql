update private.memory_publications set published_snapshot=jsonb_set(published_snapshot,'{title}','"Changed after review"') where id=current_setting('test.id')::uuid;
set local role anon;
select pg_temp.ok(public.read_memory_publication(current_setting('test.id')::uuid) is null,'changed title invalidates whole snapshot review');

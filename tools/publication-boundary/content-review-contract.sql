set local role authenticated;
select pg_temp.fails($q$select public.review_memory_publication_content(current_setting('test.id')::uuid,current_setting('test.content_hash'),'GENERAL',3,'TEST_ONLY_CONTENT')$q$,'CONTENT_POLICY_CHANGED','old reviewed policy cannot approve under current policy');

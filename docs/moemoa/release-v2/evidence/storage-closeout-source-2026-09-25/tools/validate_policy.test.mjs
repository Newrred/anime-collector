import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {validatePolicy} from './validate_policy.mjs';
const base=JSON.parse(await readFile(new URL('../config/service-policy.candidate.json',import.meta.url),'utf8'));
const copy=()=>structuredClone(base);
async function reject(name,mutate){await test(name,async()=>{const p=copy();mutate(p);assert.equal((await validatePolicy(p)).ok,false);});}
await test('candidate is well-formed but not launch approved',async()=>{const r=await validatePolicy(copy());assert.equal(r.ok,true);assert(r.warnings.length>0);assert.equal(r.variableBudgetKrw,null);});
await test('unapproved null values block release configuration review',async()=>{const r=await validatePolicy(copy(),{releasePreview:true});assert.equal(r.ok,false);assert(r.errors.some(x=>x.includes('privateReadBytesPerMonth')));});
await reject('no billing',p=>p.releaseScope.billing=true);
await reject('no ads',p=>p.releaseScope.ads=true);
await reject('no original cloud product',p=>p.releaseScope.originalCloudBackup=true);
await reject('private sync cannot be removed',p=>p.releaseScope.privateOptimizedImageSync=false);
await reject('native scope cannot be silently expanded',p=>p.releaseScope.nativeAndroid=true);
await reject('50000 budget cannot silently grow',p=>p.budget.monthlyIncrementalCeilingKrw=60000);
await reject('new shared Vercel overage counts',p=>p.budget.moemoaVercelOverageIncluded=false);
await reject('public private bucket is forbidden',p=>p.controls.privateBucketPublic=true);
await reject('unknown setting is rejected',p=>p.free.misspelledLimit=10);
await reject('negative quota',p=>p.free.privateImageQuotaBytes=-1);
await reject('string is not a byte count',p=>p.free.mainMaxBytes='1MB');
await reject('thumbnail included in transport bound',p=>p.free.transportBodyMaxBytes=1050000);
await reject('provider body cap cannot be ignored',p=>p.free.transportBodyMaxBytes=5000000);
await reject('budget forecast thresholds are ordered',p=>p.budget.warnFractionOfVariableBudget=.99);
await reject('fixed costs plus reserve exceed budget',p=>p.budget.fixedMonthlyEstimateKrw=47000);
await reject('zero monthly limit is not unlimited',p=>p.free.privateReadBytesPerMonth=0);
await reject('cannot double-count Board references',p=>p.free.countBoardReferencesAsCopies=true);
await reject('cannot auto-delete over quota',p=>p.free.autoDeleteOnQuotaExceeded=true);
await reject('client plan is not authoritative',p=>p.controls.trustClientPlanOrByteCount=true);
await reject('paid plan cannot be added secretly',p=>p.releaseScope.enabledPlanIds.push('PLUS'));
await test('numbers may be tuned without changing scope',async()=>{const p=copy();p.free.privateImageQuotaBytes=40000000;assert.equal((await validatePolicy(p)).ok,true);});
await test('filled SYNTHETIC fixture checks shape only, not evidence truth',async()=>{
 const p=copy();p.approvalState='APPROVED_FOR_CONFIG_REVIEW';p.budget.fixedMonthlyEstimateKrw=40000;
 p.free.privateReadBytesPerMonth=1000000000;p.free.publicReadBytesPerMonth=500000000;
 for(const key of Object.keys(p.globalLimits)) p.globalLimits[key]=key==='enrolledAccountCapacityMax'?100:1000000000;
 for(const key of Object.keys(p.retention)) if(p.retention[key]===null) p.retention[key]=24;
 for(const key of Object.keys(p.approvalEvidence)) p.approvalEvidence[key]='SYNTHETIC_TEST_ONLY_NOT_AN_APPROVAL';
 const r=await validatePolicy(p,{releasePreview:true});assert.equal(r.ok,true);assert.equal(r.variableBudgetKrw,5000);
 assert(r.warnings.some(x=>x.includes('NOT verified')));
});
